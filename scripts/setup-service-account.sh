#!/usr/bin/env bash
# V2.2 WP-2 (H-2): installs DIAPORIA to run under its OWN OS account, separate from the account your AI host
# (Claude Code, Codex, ...) runs as. Run it yourself with sudo, from the DIAPORIA folder. Never let an AI assistant run it.
#
#   sudo scripts/setup-service-account.sh --ai-user <your normal account> [--service-user diaporia]
#        [--prefix /opt/diaporia] [--data /var/lib/diaporia] [--etc /etc/diaporia] [--port 8790] [--user-id demo-user]
#
# What it does (Linux and WSL; macOS: do the same steps by hand, see docs/SETUP.md):
#   1. creates the system account <service-user> (no login shell, no home);
#   2. copies the code to <prefix>/app, owned by root and not writable by anyone else (the AI host cannot change it);
#   3. creates the data directory <data>, owned by <service-user>, mode 700 (the AI host cannot read or replace it);
#   4. writes <etc>/server.env (root:<service-user>, 640) with a NEW AI-client token, DIAPORIA_AI_HOST_UIDS and the
#      owner registry path, and gives the AI host account its own copy of the client token only
#      (~<ai-user>/.config/diaporia/client-token, 600);
#   5. installs <prefix>/bin/diaporia-server, which starts the server as <service-user> with that environment.
# The owner registry (<etc>/owners.json, root-owned) is created separately with scripts/owner-enroll.ts as root.
set -euo pipefail

AI_USER=""; SVC_USER="diaporia"; PREFIX="/opt/diaporia"; DATA="/var/lib/diaporia"; ETC="/etc/diaporia"; PORT="8790"; APP_USER="demo-user"
while [ $# -gt 0 ]; do
  case "$1" in
    --ai-user) AI_USER="$2"; shift 2;; --service-user) SVC_USER="$2"; shift 2;; --prefix) PREFIX="$2"; shift 2;;
    --data) DATA="$2"; shift 2;; --etc) ETC="$2"; shift 2;; --port) PORT="$2"; shift 2;; --user-id) APP_USER="$2"; shift 2;;
    *) echo "unknown option $1" >&2; exit 2;;
  esac
done
die() { echo "setup-service-account: $*" >&2; exit 2; }
[ "$(id -u)" = "0" ] || die "run with sudo (it creates an OS account and root-owned folders)"
[ -n "$AI_USER" ] || die "--ai-user <the account your AI host runs as> is required"
id "$AI_USER" >/dev/null 2>&1 || die "unknown account $AI_USER"
[ "$AI_USER" != "$SVC_USER" ] || die "the service account must differ from the AI host account"
[ "$AI_USER" != "root" ] || die "the AI host must not run as root"
SRC="$(cd "$(dirname "$0")/.." && pwd)"
[ -f "$SRC/package.json" ] && [ -d "$SRC/src" ] || die "run from a DIAPORIA checkout"
[ -d "$SRC/node_modules" ] || die "install dependencies first (npm ci) in $SRC"

# 1. service account
if ! id "$SVC_USER" >/dev/null 2>&1; then
  useradd --system --no-create-home --home-dir "$DATA" --shell /usr/sbin/nologin --user-group "$SVC_USER"
fi
SVC_UID="$(id -u "$SVC_USER")"; AI_UID="$(id -u "$AI_USER")"

# 2. code: root-owned copy (node_modules dereferenced, so no link points back into a folder the AI host owns)
install -d -o root -g root -m 755 "$PREFIX" "$PREFIX/bin"
rm -rf "$PREFIX/app.new"; install -d -o root -g root -m 755 "$PREFIX/app.new"
( cd "$SRC" && tar --exclude=.git --exclude=.data --exclude='.env*' --dereference -cf - src node_modules package.json package-lock.json tsconfig.json tsconfig.build.json 2>/dev/null ) | tar -C "$PREFIX/app.new" -xf -
chown -R root:root "$PREFIX/app.new"; chmod -R go-w,u+rwX,go+rX "$PREFIX/app.new"
rm -rf "$PREFIX/app.old"; [ -d "$PREFIX/app" ] && mv "$PREFIX/app" "$PREFIX/app.old"; mv "$PREFIX/app.new" "$PREFIX/app"; rm -rf "$PREFIX/app.old"

# 3. data
install -d -o "$SVC_USER" -g "$SVC_USER" -m 700 "$DATA"

# 4. configuration and the AI client token
install -d -o root -g root -m 755 "$ETC"
TOKEN="dct_$(head -c 24 /dev/urandom | base64 | tr '+/' '-_' | tr -d '=')"
umask 077
cat > "$ETC/server.env.new" <<EOF
HOST=127.0.0.1
PORT=$PORT
PUBLIC_BASE_URL=http://localhost:$PORT
DIAPORIA_DB_PATH=$DATA/diaporia.sqlite
DIAPORIA_OWNER_REGISTRY=$ETC/owners.json
DIAPORIA_AI_HOST_UIDS=$AI_UID
DIAPORIA_DEV_TOKENS=$TOKEN=$APP_USER
EOF
chown root:"$SVC_USER" "$ETC/server.env.new"; chmod 640 "$ETC/server.env.new"; mv "$ETC/server.env.new" "$ETC/server.env"
AI_HOME="$(getent passwd "$AI_USER" | cut -d: -f6)"
install -d -o "$AI_USER" -m 700 "$AI_HOME/.config" "$AI_HOME/.config/diaporia" 2>/dev/null || install -d -o "$AI_USER" -m 700 "$AI_HOME/.config/diaporia"
printf '%s\n' "$TOKEN" > "$AI_HOME/.config/diaporia/client-token"; chown "$AI_USER" "$AI_HOME/.config/diaporia/client-token"; chmod 600 "$AI_HOME/.config/diaporia/client-token"
umask 022

# 5. launcher (root-owned): reads the environment file and drops to the service account
NODE="$(command -v node)"
cat > "$PREFIX/bin/diaporia-server" <<EOF
#!/usr/bin/env bash
# Starts DIAPORIA as $SVC_USER (uid $SVC_UID). Generated by scripts/setup-service-account.sh.
set -euo pipefail
[ "\$(id -u)" = "0" ] || { echo "run with sudo: sudo $PREFIX/bin/diaporia-server" >&2; exit 2; }
cd "$DATA"
exec setpriv --reuid="$SVC_UID" --regid="$(id -g "$SVC_USER")" --clear-groups --reset-env -- \\
  env \$(grep -v '^#' "$ETC/server.env" | xargs) PATH=/usr/bin:/bin \\
  "$NODE" --import "file://$PREFIX/app/node_modules/tsx/dist/esm/index.mjs" "$PREFIX/app/src/main.ts"
EOF
chown root:root "$PREFIX/bin/diaporia-server"; chmod 755 "$PREFIX/bin/diaporia-server"

echo "DIAPORIA service account set up:"
echo "  service account : $SVC_USER (uid $SVC_UID)"
echo "  AI host account : $AI_USER (uid $AI_UID), client token in $AI_HOME/.config/diaporia/client-token"
echo "  code            : $PREFIX/app (root-owned; re-run this script after updating the checkout)"
echo "  data            : $DATA (700, $SVC_USER)"
echo "Next: create the owner registry as root (docs/SETUP.md, \"Owner confirmation\"), then start with: sudo $PREFIX/bin/diaporia-server"
